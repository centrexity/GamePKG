//! Host-owned bitmap font compatibility implementation.
//!
//! This crate is deliberately dependency-free and is linked only into the
//! GamePKG host. Games receive glyph pixels through the audited port service;
//! they never add this crate, load a font file or call a platform font API.

pub const CELL_WIDTH: u32 = 5;
pub const CELL_HEIGHT: u32 = 7;
pub const MAX_SIZE: u32 = 32;

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Glyph {
    /// Raster width in pixels.
    pub width: u32,
    /// Raster height in pixels.
    pub height: u32,
    /// Advance in pixels for this glyph at the requested size.
    pub advance: u32,
    /// Straight-alpha RGBA8 pixels, row-major, tightly packed.
    pub rgba: Vec<u8>,
}

impl Glyph {
    pub fn byte_len(&self) -> usize {
        self.rgba.len()
    }
}

/// Return the five column bits for a printable ASCII glyph. The table is a
/// GamePKG-owned 5x7 bitmap; a missing codepoint uses the replacement box.
pub fn pattern(codepoint: u32) -> [u8; CELL_WIDTH as usize] {
    match codepoint {
        0x20 => [0, 0, 0, 0, 0],
        0x21 => [0, 0, 0x5f, 0, 0],
        0x22 => [0, 0x07, 0, 0x07, 0],
        0x23 => [0x14, 0x7f, 0x14, 0x7f, 0x14],
        0x24 => [0x24, 0x2a, 0x7f, 0x2a, 0x12],
        0x25 => [0x23, 0x13, 0x08, 0x64, 0x62],
        0x26 => [0x36, 0x49, 0x55, 0x22, 0x50],
        0x27 => [0, 0x05, 0x03, 0, 0],
        0x28 => [0, 0x1c, 0x22, 0x41, 0],
        0x29 => [0, 0x41, 0x22, 0x1c, 0],
        0x2a => [0x14, 0x08, 0x3e, 0x08, 0x14],
        0x2b => [0x08, 0x08, 0x3e, 0x08, 0x08],
        0x2c => [0, 0x50, 0x30, 0, 0],
        0x2d => [0x08, 0x08, 0x08, 0x08, 0x08],
        0x2e => [0, 0x60, 0x60, 0, 0],
        0x2f => [0x20, 0x10, 0x08, 0x04, 0x02],
        0x30..=0x39 => digit(codepoint - 0x30),
        0x3a => [0, 0x36, 0x36, 0, 0],
        0x3b => [0, 0x56, 0x36, 0, 0],
        0x3c => [0x08, 0x14, 0x22, 0x41, 0],
        0x3d => [0x14, 0x14, 0x14, 0x14, 0x14],
        0x3e => [0, 0x41, 0x22, 0x14, 0x08],
        0x3f => [0x02, 0x01, 0x51, 0x09, 0x06],
        0x40 => [0x32, 0x49, 0x79, 0x41, 0x3e],
        0x41..=0x5a => upper(codepoint - 0x41),
        0x5b => [0, 0x7f, 0x41, 0x41, 0],
        0x5c => [0x02, 0x04, 0x08, 0x10, 0x20],
        0x5d => [0, 0x41, 0x41, 0x7f, 0],
        0x5e => [0x04, 0x02, 0x01, 0x02, 0x04],
        0x5f => [0x40, 0x40, 0x40, 0x40, 0x40],
        0x60 => [0, 0x01, 0x02, 0x04, 0],
        0x61..=0x7a => lower(codepoint - 0x61),
        0x7b => [0, 0x1c, 0x22, 0x41, 0],
        0x7c => [0, 0x7f, 0, 0x7f, 0],
        0x7d => [0, 0x41, 0x22, 0x1c, 0],
        0x7e => [0x10, 0x08, 0x08, 0x10, 0x08],
        _ => [0x3e, 0x41, 0x45, 0x49, 0x3e],
    }
}

fn digit(index: u32) -> [u8; 5] {
    match index {
        0 => [0x3e, 0x51, 0x49, 0x45, 0x3e],
        1 => [0, 0x42, 0x7f, 0x40, 0],
        2 => [0x42, 0x61, 0x51, 0x49, 0x46],
        3 => [0x21, 0x41, 0x45, 0x4b, 0x31],
        4 => [0x18, 0x14, 0x12, 0x7f, 0x10],
        5 => [0x27, 0x45, 0x45, 0x45, 0x39],
        6 => [0x3c, 0x4a, 0x49, 0x49, 0x30],
        7 => [0x01, 0x71, 0x09, 0x05, 0x03],
        8 => [0x36, 0x49, 0x49, 0x49, 0x36],
        _ => [0x06, 0x49, 0x49, 0x29, 0x1e],
    }
}

