/// Rasterize one glyph into bounded straight-alpha RGBA8 pixels. Size is the
/// nearest-neighbor scale of each 5x7 cell bit and is capped at `MAX_SIZE`.
pub fn rasterize(codepoint: u32, size: u32) -> Option<Glyph> {
    if size == 0 || size > MAX_SIZE {
        return None;
    }
    let columns = pattern(codepoint);
    let width = CELL_WIDTH * size;
    let height = CELL_HEIGHT * size;
    let mut rgba = vec![0u8; (width * height * 4) as usize];
    for column in 0..CELL_WIDTH as usize {
        for row in 0..CELL_HEIGHT as usize {
            if columns[column] & (1 << row) == 0 {
                continue;
            }
            for scale_y in 0..size {
                let start = ((((row as u32 * size + scale_y) * width) + column as u32 * size)
                    as usize)
                    * 4;
                for scale_x in 0..size {
                    let pixel = start + scale_x as usize * 4;
                    rgba[pixel..pixel + 4].copy_from_slice(&[0xff, 0xff, 0xff, 0xff]);
                }
            }
        }
    }
    Some(Glyph {
        width,
        height,
        advance: (CELL_WIDTH + 1) * size,
        rgba,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn glyph_raster_is_bounded_and_deterministic() {
        let a = rasterize('A' as u32, 2).unwrap();
        assert_eq!((a.width, a.height, a.advance), (10, 14, 12));
        assert_eq!(a.rgba.len(), 10 * 14 * 4);
        assert_eq!(a.byte_len(), a.rgba.len());
        assert_eq!(a, rasterize('A' as u32, 2).unwrap());
        assert_ne!(a, rasterize('B' as u32, 2).unwrap());
        assert!(a.rgba.chunks_exact(4).any(|p| p[3] == 0xff));
        assert!(rasterize('A' as u32, 0).is_none());
        assert!(rasterize('A' as u32, MAX_SIZE + 1).is_none());
        assert_eq!(pattern('!' as u32), [0, 0, 0x5f, 0, 0]);
    }
}
