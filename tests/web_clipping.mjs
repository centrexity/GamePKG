import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const worker=vm.createContext({TextEncoder,TextDecoder});
vm.runInContext(readFileSync(new URL('../web-player/worker.js',import.meta.url),'utf8'),worker);
const api=vm.runInContext('({api,canonical,state:()=>({commands,imageBudget}),reset:()=>{commands=[];imageBudget=0;}})',worker);
for(const bounds of [[NaN,0,1,1],[-1,0,1,1],[0,0,641,1],[0,480,1,1],[0,0,-1,1],[Infinity,0,0,0]])assert.equal(api.api.draw_clip(...bounds),-1);
assert.equal(api.api.draw_clip(0,0,0,0),0);
assert.equal(api.canonical['draw-clip'](1,2,3,4),1);
assert.equal(api.canonical['draw-clip-reset'](),1);
assert.deepEqual(JSON.parse(JSON.stringify(api.state().commands)),[['clip',0,0,0,0],['clip',1,2,3,4],['clip-reset']]);
api.reset();for(let i=0;i<1024;i++)assert.equal(api.api.draw_clip_reset(),0);
assert.equal(api.api.draw_clip(0,0,640,480),-1);
assert.equal(api.canonical['draw-clip-reset'](),0);
vm.runInContext('imageBudget=8388608',worker);
assert.equal(api.api.draw_clear(0x123456ff),0);
assert.equal(api.state().commands.length,0);
assert.equal(api.state().imageBudget,8388608);
let depth=0;const clips=[];
const context={save(){depth++;},restore(){assert.ok(depth>0);depth--;},fillRect(){},beginPath(){},rect(...bounds){clips.push(bounds);},clip(){}};
const ui=vm.createContext({context,color:()=> '#000',canvas:{dataset:{}},data:{custom_renderer:true},document:{querySelector:()=>({textContent:''})}});
const player=readFileSync(new URL('../web-player/player.js',import.meta.url),'utf8');
vm.runInContext(player.slice(player.indexOf('function render(frame)'),player.indexOf('function playAudio(')),ui);
vm.runInContext("render({background:null,state:'0',commands:[['clip',1,2,3,4],['clip',5,6,7,8],['clip-reset']]});render({background:null,state:'1',commands:[]});",ui);
assert.equal(depth,0);assert.deepEqual(clips,[[1,2,3,4],[5,6,7,8]]);
console.log('Clip validation, replacement/reset, command bounds, clear accounting and balanced browser frame state passed.');
